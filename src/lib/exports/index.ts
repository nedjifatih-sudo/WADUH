import * as XLSX from "xlsx";
import jsPDF from "jspdf";
import autoTable from "jspdf-autotable";
import { formatDateTime } from "@/lib/utils";

export interface ReportMeta {
  organizationName: string;
  reportTitle: string;
  dateRange?: string;
  generatedBy?: string;
  filterSummary?: string;
}

/**
 * Export table data to CSV file
 */
export function exportToCSV(filename: string, rows: Record<string, any>[]) {
  if (!rows || rows.length === 0) return;
  const worksheet = XLSX.utils.json_to_sheet(rows);
  const csvContent = XLSX.utils.sheet_to_csv(worksheet);
  const blob = new Blob([csvContent], { type: "text/csv;charset=utf-8;" });
  const url = URL.createObjectURL(blob);
  const link = document.createElement("a");
  link.setAttribute("href", url);
  link.setAttribute("download", `${filename}_${Date.now()}.csv`);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
}

/**
 * Export table data to Excel (.xlsx) file
 */
export function exportToExcel(
  filename: string,
  sheetName: string,
  rows: Record<string, any>[]
) {
  if (!rows || rows.length === 0) return;
  const worksheet = XLSX.utils.json_to_sheet(rows);
  const workbook = XLSX.utils.book_new();
  XLSX.utils.book_append_sheet(workbook, worksheet, sheetName.slice(0, 31));
  XLSX.writeFile(workbook, `${filename}_${Date.now()}.xlsx`);
}

/**
 * Export report to formatted PDF document with official enterprise header
 */
export function exportToPDF(
  meta: ReportMeta,
  columns: { header: string; dataKey: string }[],
  data: Record<string, any>[]
) {
  const doc = new jsPDF("landscape", "mm", "a4");

  // Enterprise Header
  doc.setFillColor(17, 24, 39); // #111827 Dark Navy
  doc.rect(0, 0, 297, 20, "F");

  doc.setTextColor(255, 255, 255);
  doc.setFontSize(14);
  doc.setFont("helvetica", "bold");
  doc.text("INVENTORY OS", 14, 13);

  doc.setFontSize(10);
  doc.setFont("helvetica", "normal");
  doc.text(meta.organizationName.toUpperCase(), 70, 13);

  doc.setTextColor(17, 24, 39);
  doc.setFontSize(16);
  doc.setFont("helvetica", "bold");
  doc.text(meta.reportTitle, 14, 32);

  doc.setFontSize(9);
  doc.setFont("helvetica", "normal");
  doc.setTextColor(100, 116, 139);

  const genDate = `Generated: ${formatDateTime(new Date())}`;
  const genBy = `Generated By: ${meta.generatedBy || "Authorized System User"}`;
  const range = meta.dateRange ? `Period: ${meta.dateRange}` : "Period: All Available Records";
  const filters = meta.filterSummary ? `Filters: ${meta.filterSummary}` : "";

  doc.text(`${genDate}  |  ${genBy}`, 14, 38);
  doc.text(`${range} ${filters ? ` |  ${filters}` : ""}`, 14, 43);

  // Table
  autoTable(doc, {
    startY: 48,
    columns: columns.map((col) => ({ header: col.header, dataKey: col.dataKey })),
    body: data,
    theme: "striped",
    headStyles: {
      fillColor: [37, 99, 235], // #2563EB Blue
      textColor: [255, 255, 255],
      fontSize: 9,
      fontStyle: "bold",
    },
    bodyStyles: {
      fontSize: 8,
      textColor: [30, 41, 59],
    },
    alternateRowStyles: {
      fillColor: [248, 250, 252],
    },
    margin: { top: 48, left: 14, right: 14, bottom: 20 },
    didDrawPage: (dataInfo) => {
      // Footer page numbering
      const pageCount = (doc as any).internal.getNumberOfPages();
      doc.setFontSize(8);
      doc.setTextColor(148, 163, 184);
      doc.text(
        `Page ${dataInfo.pageNumber} of ${pageCount} — Confidential Enterprise Document`,
        14,
        205
      );
    },
  });

  doc.save(`${meta.reportTitle.toLowerCase().replace(/\s+/g, "_")}_${Date.now()}.pdf`);
}
